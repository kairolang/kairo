"""Shift semantics, run on every target at every level (SHIFT spec §8.1, §8.2).

Usage: shift_run.py <workdir> <qemu-arm> <qemu-aarch64> <qemu-riscv64> -- <kairo command...>

The expected table comes from REF below, a reference implementation of the
spec's §1 written here, never from the compiler:

    R = 32 for W <= 32, 64 for W <= 64; c = n mod R (n converted modulo 2^R)
    x << n   (x << c) truncated to T
    x >> n   logical for unsigned T, arithmetic (sign fill) for signed T

For each T in u8 i8 u16 i16 u32 i32 u64 i64 the generated cases.k exports
`x << n`, `x >> n`, `x <<= n` and `x >>= n`, each reading its count through a
volatile load so no level folds it, and the generated host.k calls every case
over x in {1, -1 if signed, 0x81 truncated to T} and the spec's counts. Each
target builds both at -O0, -O1, -O2 and -Oz; every one of the 24 runs must
print exactly the reference table.

    target                  cases built for            linked into          run by
    x86_64                  the host triple            the host program     the host
    aarch64-linux-musl      itself                     itself, static       qemu-aarch64
    riscv64-linux-musl      itself                     itself, static       qemu-riscv64
    armv7-linux-musleabihf  itself                     itself, static       qemu-arm
    thumbv7m-none-eabi      itself (-c, freestanding)  the armv7 program    qemu-arm
    thumbv6m-none-eabi      itself (-c, freestanding)  the armv7 program    qemu-arm

No system emulator is available for the M-profile parts, so their objects run
inside an armv7 Linux program under qemu-arm: the thumbv6m / thumbv7m machine
code itself executes (ARMv7-A in Thumb state implements every ARMv6-M and
ARMv7-M instruction it uses, with the same register-count shift rule: the
count's low byte), only the harness around it is A-profile.

The eval table (§8.4) is a third program: an `eval fn` per case, all of
them hashed (FNV-1a over the results) by an `eval fn` that initializes an
`eval` constant, so clang's constant evaluator computes every value; a
second hash covers literal counts below the width (the constant, no_wrap
form). Built once for the host; both hashes must equal the reference's.
"""
import concurrent.futures
import os
import subprocess
import sys

TYPES = [("u8", 8, False), ("i8", 8, True), ("u16", 16, False), ("i16", 16, True),
         ("u32", 32, False), ("i32", 32, True), ("u64", 64, False), ("i64", 64, True)]
OPS = ["shl", "shr", "shla", "shra"]
LEVELS = ["-O0", "-O1", "-O2", "-Oz"]


def counts(w):
    out = []
    for n in [0, 1, w - 1, w, w + 1, 31, 32, 33, 63, 64, 65, 255, 256, 257, -1]:
        if n not in out:
            out.append(n)
    return out


def xs(w, signed):
    v = 0x81 & ((1 << w) - 1)
    if signed and v >= (1 << (w - 1)):
        v -= 1 << w
    return [1, -1, v] if signed else [1, v]


def wrap(v, w, signed):
    v &= (1 << w) - 1
    if signed and v >= (1 << (w - 1)):
        v -= 1 << w
    return v


def REF(op, w, signed, x, n):
    r = 32 if w <= 32 else 64
    c = n % r
    if op in ("shl", "shla"):
        return wrap(x << c, w, signed)
    if signed:
        return wrap(x >> c, w, signed)
    return x >> c


def lit(v, t):
    return f"({v}{t})" if v < 0 else f"{v}{t}"


def _dispatch(prefix, kw):
    """`fn <prefix>case(t, op, x, n) -> i64` over every (type, operator)."""
    out = [f"{kw}fn {prefix}case(t: i32, o: i32, x: i64, n: i32) -> i64 {{"]
    for ti, (t, _, _) in enumerate(TYPES):
        for oi, op in enumerate(OPS):
            call = f"{prefix}{op}_{t}(x, n)" if t == "i64" else f"{prefix}{op}_{t}(x as {t}, n) as i64"
            out.append(f"    if (t == {ti}) && (o == {oi}) {{ return {call} }}")
    out.append("    return 0")
    out.append("}")
    return out


def gen_cases():
    sym = {"shl": "<<", "shr": ">>", "shla": "<<=", "shra": ">>="}
    out = ["// Generated by shift_run.py: one function per (type, operator), and", "// k_case dispatching to them.", ""]
    for t, _, _ in TYPES:
        for op in OPS:
            out.append(f"fn k_{op}_{t}(x: {t}, n: i32) -> {t} {{")
            out.append("    var c: i32 = n")
            out.append("    var m: i32 = 0")
            out.append("    unsafe { m = *(&c as unsafe *volatile i32) }")
            if op in ("shl", "shr"):
                out.append(f"    return x {sym[op]} m")
            else:
                out.append("    var y = x")
                out.append(f"    y {sym[op]} m")
                out.append("    return y")
            out.append("}")
    out += _dispatch("k_", 'ffi "c" ')
    return "\n".join(out) + "\n"


def _arr(name, ty, vals):
    return f"    var {name}: [{ty}; {len(vals)}] = [{', '.join(str(v) for v in vals)}]"


def _loops(call):
    """Every case in table order: type, operator, x, n."""
    out = []
    for ti, (t, w, signed) in enumerate(TYPES):
        x, n = xs(w, signed), counts(w)
        out.append(_arr(f"xs{ti}", "i64", x))
        out.append(_arr(f"ns{ti}", "i32", n))
        out.append(f"    for o in 0..4 {{ for xi in 0..{len(x)} {{ for ni in 0..{len(n)} {{")
        out.append("        " + call(ti))
        out.append("    } } }")
    return out


def gen_main():
    out = ["// Generated by shift_run.py.", "import std::io::*", "",
           'ffi "c" fn k_case(t: i32, o: i32, x: i64, n: i32) -> i64', "",
           "fn main() -> i32 {"]
    out += _loops(lambda ti: f'println(f"{{k_case({ti}, o, xs{ti}[xi], ns{ti}[ni])}}")')
    out.append("    return 0")
    out.append("}")
    return "\n".join(out) + "\n"


FNV_OFF = 14695981039346656037
FNV_PRIME = 1099511628211


def fnv(h, v):
    return ((h ^ (v & ((1 << 64) - 1))) * FNV_PRIME) & ((1 << 64) - 1)


def literal_cases():
    """(type, op, x, n) with a literal count below the width: the constant form."""
    out = []
    for t, w, signed in TYPES:
        for op in ("shl", "shr"):
            for x in xs(w, signed):
                for n in sorted({0, 1, 3, w - 1}):
                    out.append((t, w, signed, op, x, n))
    return out


def gen_eval():
    """The table in clang's constant evaluator: every case's value hashed by
    an `eval fn` whose result initializes an `eval` constant, so none of it
    runs at run time. A literal count below the width is the constant
    (no_wrap) form."""
    sym = {"shl": "<<", "shr": ">>"}
    out = ["// Generated by shift_run.py.", "import std::io::*", ""]
    for t, _, _ in TYPES:
        for op in OPS:
            if op in ("shl", "shr"):
                out.append(f"eval fn ev_{op}_{t}(x: {t}, n: i32) -> {t} {{ return x {sym[op]} n }}")
            else:
                s_ = "<<=" if op == "shla" else ">>="
                out.append(f"eval fn ev_{op}_{t}(x: {t}, n: i32) -> {t} {{ var y = x; y {s_} n; return y }}")
    out += _dispatch("ev_", "eval ")
    out.append("eval fn mix(h: u64, v: i64) -> u64 { return (h ^ (v as u64)) * " + f"{FNV_PRIME}u64" + " }")
    out.append("")
    out.append("eval fn table() -> u64 {")
    out.append(f"    var h: u64 = {FNV_OFF}u64")
    out += _loops(lambda ti: f"h = mix(h, ev_case({ti}, o, xs{ti}[xi], ns{ti}[ni]))")
    out.append("    return h")
    out.append("}")
    out.append("")
    out.append("eval fn literals() -> u64 {")
    out.append(f"    var h: u64 = {FNV_OFF}u64")
    for t, w, signed, op, x, n in literal_cases():
        v = f"({lit(x, t)} {sym[op]} {n})"
        out.append(f"    h = mix(h, {v})" if t == "i64" else f"    h = mix(h, {v} as i64)")
    out.append("    return h")
    out.append("}")
    out.append("")
    out.append("eval TABLE: u64 = table()")
    out.append("eval LITERALS: u64 = literals()")
    out.append("")
    out.append("fn main() -> i32 {")
    out.append('    println(f"{TABLE}")')
    out.append('    println(f"{LITERALS}")')
    out.append("    return 0")
    out.append("}")
    return "\n".join(out) + "\n"


def expected():
    out = []
    for t, w, signed in TYPES:
        for op in OPS:
            for x in xs(w, signed):
                for n in counts(w):
                    # Every result comes back as an i64.
                    out.append(str(wrap(REF(op, w, signed, x, n), 64, True)))
    return out


def expected_eval():
    h = FNV_OFF
    for t, w, signed in TYPES:
        for op in OPS:
            for x in xs(w, signed):
                for n in counts(w):
                    h = fnv(h, REF(op, w, signed, x, n))
    h2 = FNV_OFF
    for t, w, signed, op, x, n in literal_cases():
        h2 = fnv(h2, REF(op, w, signed, x, n))
    return [str(h), str(h2)]


def labels():
    out = []
    for t, w, signed in TYPES:
        for op in OPS:
            for x in xs(w, signed):
                for n in counts(w):
                    out.append(f"{t} {op} x={x} n={n}")
    return out


def run(cmd, what):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"{what}: exit {r.returncode}\n$ {' '.join(cmd)}\n{r.stdout[-3000:]}\n{r.stderr[-3000:]}")
    return r.stdout


def main():
    sep = sys.argv.index("--")
    work, qarm, qa64, qrv = sys.argv[1:sep]
    kairo = sys.argv[sep + 1:]
    os.makedirs(work, exist_ok=True)
    cases = os.path.join(work, "cases.k")
    # Not main.k: a file's module is its stem, and `main` the module
    # collides with `main` the function.
    mainf = os.path.join(work, "host.k")
    evalf = os.path.join(work, "eval.k")
    open(cases, "w").write(gen_cases())
    open(mainf, "w").write(gen_main())
    open(evalf, "w").write(gen_eval())

    # name -> (cases target or None for the host, freestanding+mcpu, program target, runner)
    targets = [
        ("x86_64", None, [], None, []),
        ("aarch64", "aarch64-linux-musl", [], "aarch64-linux-musl", [qa64]),
        ("riscv64", "riscv64-linux-musl", [], "riscv64-linux-musl", [qrv]),
        ("armv7a", "armv7-linux-musleabihf", [], "armv7-linux-musleabihf", [qarm]),
        ("thumbv7m", "thumbv7m-none-eabi", ["--freestanding", "-mcpu=cortex-m3"], "armv7-linux-musleabihf", [qarm]),
        ("thumbv6m", "thumbv6m-none-eabi", ["--freestanding", "-mcpu=cortex-m0plus"], "armv7-linux-musleabihf", [qarm]),
    ]
    want = expected()
    names = labels()

    def job(tgt, level):
        name, ct, cflags, pt, runner = tgt
        d = os.path.join(work, f"{name}{level}")
        os.makedirs(d, exist_ok=True)
        obj = os.path.join(d, "cases.o")
        exe = os.path.join(d, "main.exe")
        tflag = ["--target", ct] if ct else []
        pflag = ["--target", pt] if pt else []
        # A freestanding build takes the bare binary: the hosted roots %kairo
        # names pull in Lib/rt, which needs a libc (Tests/demo/lit.local.cfg).
        kc = ([kairo[0], "--error-format=basic"] if "--freestanding" in cflags else kairo)
        run(kc + cflags + tflag + [level, "-c", cases, "-o", obj, "--cache-dir", os.path.join(d, "c1")], f"{name} {level}: cases")
        run(kairo + pflag + [level, mainf, obj, "-o", exe, "--cache-dir", os.path.join(d, "c2")], f"{name} {level}: main")
        got = run(runner + [exe], f"{name} {level}: run").splitlines()
        return name, level, got

    bad = 0
    outputs = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=min(12, os.cpu_count() or 4)) as ex:
        futs = [ex.submit(job, t, l) for t in targets for l in LEVELS]
        for f in futs:
            try:
                name, level, got = f.result()
            except RuntimeError as e:
                print(f"shift_run: {e}")
                bad += 1
                continue
            outputs[(name, level)] = got
            if got != want:
                bad += 1
                diffs = [(nm, w_, g) for nm, w_, g in zip(names, want, got) if w_ != g]
                print(f"{name} {level}: {len(diffs)} result(s) differ from the reference"
                      + ("" if len(got) == len(want) else f" ({len(got)} lines, want {len(want)})"))
                for nm, w_, g in diffs[:12]:
                    print(f"  {nm}: want {w_}, got {g}")

    # eval: the host only, constant-evaluated.
    try:
        exe = os.path.join(work, "eval.exe")
        run(kairo + ["-O0", evalf, "-o", exe, "--cache-dir", os.path.join(work, "c3")], "eval: build")
        got = run([exe], "eval: run").splitlines()
        want_e = expected_eval()
        if got != want_e:
            bad += 1
            print(f"eval: hashes {got}, want {want_e} (table, literal counts)")
    except RuntimeError as e:
        print(f"shift_run: {e}")
        bad += 1

    n = len(outputs)
    print(f"shift_run: OK ({n} builds, {len(want)} results each, identical)" if bad == 0
          else f"shift_run: {bad} failure(s)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
