#!/usr/bin/env python3
"""Writes Lib/builtin2/base/text_float_tables.k: the 128-bit powers of ten shared by the float
printer (Schubfach) and the float parser (Eisel-Lemire).

Entry q holds 10^q as a 128-bit significand sig with 2^127 <= sig < 2^128:
10^q = beta * 2^r with beta in [2^127, 2^128). The stored value is

    q in [0, 55]     beta itself (5^q fits 128 bits, so it is exact)
    q > 55           floor(beta)
    q in [-27, -1]   ceil(beta)   = floor(2^b / 5^-q) + 1
    q < -27          floor(beta)

which is the table of Lemire's "Number Parsing at a Gigabyte per Second"
(the fast_float generator, extended to q = 324 for the printer). The printer
needs ceil(beta); every assertion below is a fact it relies on to derive it
from the stored value with one add.
"""
import os
import sys

QMIN, QMAX = -342, 324
M128 = (1 << 128) - 1


def beta_exact(q):
    """(floor(beta), exact?) for 10^q normalized to 128 bits."""
    if q >= 0:
        v = 5 ** q
        bl = v.bit_length()
        if bl <= 128:
            return v << (128 - bl), True
        sh = bl - 128
        return v >> sh, (v & ((1 << sh) - 1)) == 0
    p = 5 ** -q
    # beta = 2^b / p with b chosen so the quotient has 128 bits.
    b = p.bit_length() + 127
    fl = (1 << b) // p
    if fl >> 128:
        b -= 1
        fl = (1 << b) // p
    assert fl.bit_length() == 128
    return fl, False                      # 5^n never divides a power of two


def fast_float_entry(q):
    """The value fast_float's table generator stores for 5^q."""
    if q >= 0:
        v = 5 ** q
        while v < (1 << 127):
            v *= 2
        while v >= (1 << 128):
            v //= 2
        return v
    p = 5 ** -q
    z = 0
    while (1 << z) < p:
        z += 1
    if q >= -27:
        return (1 << (z + 127)) // p + 1
    c = (1 << (2 * z + 128)) // p + 1
    while c >= (1 << 128):
        c //= 2
    return c


def main():
    rows = []
    for q in range(QMIN, QMAX + 1):
        fl, exact = beta_exact(q)
        e = fast_float_entry(q)
        assert (1 << 127) <= e <= M128
        if 0 <= q <= 55:
            assert exact and e == fl, q
        elif q > 55:
            assert not exact and e == fl, q
        elif q >= -27:
            assert e == fl + 1, q
        else:
            assert e == fl, q
        hi, lo = e >> 64, e & ((1 << 64) - 1)

        # The printer's 128-bit ceil(beta): the entry, plus one where the
        # entry is a floor of an inexact value. The add never carries.
        ceil128 = fl if exact else fl + 1
        adj = 1 if (q > 55 or q < -27) else 0
        assert e + adj == ceil128, q
        assert lo + adj <= (1 << 64) - 1, q

        # The f32 printer's 64-bit ceil(beta / 2^64): the high word, plus
        # one unless the entry is exact with a zero low word.
        ceil64 = (fl >> 64) + (0 if (exact and (fl & ((1 << 64) - 1)) == 0) else 1)
        adj64 = 0 if 0 <= q <= 27 else 1
        assert hi + adj64 == ceil64, q
        assert ceil64 < (1 << 64), q
        if 0 <= q <= 27:
            assert lo == 0, q
        rows.append((hi, lo, q))

    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "Lib", "builtin2", "base", "text_float_tables.k")
    with open(out, "w") as f:
        f.write("/// builtin/base/text_float_tables.k\n")
        f.write("///\n")
        f.write("/// Generated by Scripts/gen_float_text_tables.py; do not edit.\n")
        f.write("///\n")
        f.write("/// 10^q for q in [NUMTEXT_POW10_MIN, NUMTEXT_POW10_MAX] as a 128-bit\n")
        f.write("/// significand, high word then low word: 10^q = sig * 2^r with\n")
        f.write("/// 2^127 <= sig < 2^128. The value is exact for q in [0, 55], rounded up\n")
        f.write("/// for q in [-27, -1] and rounded down everywhere else.\n\n")
        f.write("prot eval NUMTEXT_POW10_MIN: i32 = %d\n" % QMIN)
        f.write("prot eval NUMTEXT_POW10_MAX: i32 = %d\n\n" % QMAX)
        f.write("prot static const NUMTEXT_POW10: [u64; %d] = [\n" % (2 * len(rows)))
        for hi, lo, q in rows:
            f.write("    0x%016x, 0x%016x,   // 1e%d\n" % (hi, lo, q))
        f.write("]\n")
    print("wrote", out, len(rows), "entries")


if __name__ == "__main__":
    sys.exit(main())
