#!/usr/bin/env python3
"""Generates the self-checking f256 / f512 lit tests.

Each test runs a deterministic stream of operands, the SAME stream this script
draws (xorshift64*, mirrored below and in the test's Kairo), through every
operation, and folds every result's bits (and every formatted string's bytes)
into one FNV-1a hash per operation. The expected hashes come from an exact
oracle (fractions.Fraction and big integers, round to nearest even once),
Scripts/softfloat_oracle/wfo.py and textor.py. So thousands of vectors cost
a few lines of source, and a mismatch names the operation; rerun with the dev
harness (Scripts/softfloat_oracle/run_*.py) to see the vectors.

usage: python3 Scripts/gen_softfloat_tests.py [--oracle DIR] [--out Tests/Codegen]
"""
import argparse
import os
import sys

MASK64 = (1 << 64) - 1
FNV0 = 0xcbf29ce484222325
FNVP = 0x100000001b3


class Rng:
    def __init__(self, s):
        self.s = s

    def next(self):
        x = self.s
        x ^= x >> 12
        x ^= (x << 25) & MASK64
        x ^= x >> 27
        self.s = x
        return (x * 2685821657736338717) & MASK64

    def bits(self, k):
        v, got = 0, 0
        while got < k:
            v = (v << 64) | self.next()
            got += 64
        return v & ((1 << k) - 1)


def gen(f, r, near=None, moderate=False):
    """One encoding; mirrored by the test's gen_()."""
    nb, mb, emask, bias = f.nbits, f.mbits, f.emask, f.bias
    sign = (r.next() & 1) << (nb - 1)
    k = r.next() % 100
    if moderate:
        k = 50 + k % 50
    if k < 3:
        return f.qnan()
    if k < 6:
        return sign | (emask << mb)
    if k < 9:
        return sign
    if k < 15:
        n = 1 + r.next() % mb
        return sign | r.bits(n)
    if k < 20:
        e = 1 + r.next() % 4
    elif k < 25:
        e = emask - 1 - r.next() % 4
    elif k < 40:
        e = bias - 8 + r.next() % 17
    elif k < 50 and near is not None and 0 < ((near >> mb) & emask) < emask:
        ne = (near >> mb) & emask
        e = ne - 2 + r.next() % 5
        e = max(1, min(emask - 1, e))
        m = (near & ((1 << mb) - 1)) ^ r.bits(1 + r.next() % 12)
        return sign | (e << mb) | m
    elif moderate:
        e = bias - 3000 + r.next() % 6001
    else:
        e = 1 + r.next() % (emask - 1)
    p = r.next() % 10
    if p == 0:
        m = (1 << mb) - 1
    elif p == 1:
        m = 1 << (r.next() % mb)
    elif p == 2:
        m = r.bits(8) << (mb - 8)
    else:
        m = r.bits(mb)
    return sign | (e << mb) | m


def fnv(h, v, nbytes):
    for i in range(nbytes // 8):
        h = ((h ^ ((v >> (64 * i)) & MASK64)) * FNVP) & MASK64
    return h


def fnv_str(h, s):
    for c in s.encode():
        h = ((h ^ c) * FNVP) & MASK64
    return h


TEMPLATE = r'''// @F@: the arithmetic, comparisons and conversions of the primitive, bit
// for bit against an exact oracle. A deterministic stream of @N@ operand
// triples (xorshift64*, weighted to NaN, infinities, zeros, subnormals, both
// ends of the exponent range and near-cancelling pairs) goes through every
// operation, and each operation's results are folded into one FNV-1a hash,
// compared with the hash Scripts/gen_softfloat_tests.py computed from
// fractions.Fraction (round to nearest even, once). Text is checked the same
// way, and every finite value's shortest text must parse back to its bits.
// Generated by Scripts/gen_softfloat_tests.py; regenerate, do not edit.

import std::io

struct Rng {
    var s: u64 = 0
}

fn next_(r: *Rng) -> u64 {
    var x = r->s
    x = x ^ (x >> 12)
    x = x ^ (x << 25)
    x = x ^ (x >> 27)
    r->s = x
    return x * 2685821657736338717
}

fn bits_(r: *Rng, k: i32) -> u512 {
    var v: u512 = 0
    var got: i32 = 0
    while got < k {
        v = (v << 64) | (next_(r) as u512)
        got += 64
    }
    if k < 512 {
        var one: u512 = 1
        v = v & ((one << (k as u32)) - 1)
    }
    return v
}

fn gen_(r: *Rng, near: u512, has_near: bool, moderate: bool) -> u512 {
    var nb: u32 = @W@
    var mb: u32 = @M@
    var emask: u512 = @EMASK@
    var bias: u512 = @BIAS@
    var one: u512 = 1
    var sign = ((next_(r) & 1) as u512) << (nb - 1)
    var k = next_(r) % 100
    if moderate { k = 50 + k % 50 }
    if k < 3 { return (emask << mb) | (one << (mb - 1)) }
    if k < 6 { return sign | (emask << mb) }
    if k < 9 { return sign }
    if k < 15 {
        var n = 1 + next_(r) % (mb as u64)
        return sign | bits_(r, n as i32)
    }
    var e: u512 = 0
    var ne = (near >> mb) & emask
    if k < 20 {
        e = (1 + next_(r) % 4) as u512
    } else if k < 25 {
        e = emask - 1 - ((next_(r) % 4) as u512)
    } else if k < 40 {
        e = bias - 8 + ((next_(r) % 17) as u512)
    } else if k < 50 && has_near && ne > 0 && ne < emask {
        e = ne + ((next_(r) % 5) as u512)
        if e < 3 { e = 1 } else { e = e - 2 }
        if e > emask - 1 { e = emask - 1 }
        var nbits = 1 + next_(r) % 12
        var m = (near & ((one << mb) - 1)) ^ bits_(r, nbits as i32)
        return sign | (e << mb) | m
    } else if moderate {
        e = bias - 3000 + ((next_(r) % 6001) as u512)
    } else {
        e = 1 + ((next_(r) % ((emask - 1) as u64)) as u512)
    }
    var p = next_(r) % 10
    var m: u512 = 0
    if p == 0 {
        m = (one << mb) - 1
    } else if p == 1 {
        m = one << ((next_(r) % (mb as u64)) as u32)
    } else if p == 2 {
        m = bits_(r, 8) << (mb - 8)
    } else {
        m = bits_(r, mb as i32)
    }
    return sign | (e << mb) | m
}

fn fnv_(h: *u64, v: u512, nbytes: i32) {
    for var i: i32 = 0; i < nbytes / 8; ++i {
        var c = ((v >> ((64 * i) as u32)) as u64)
        var x = *h
        *h = (x ^ c) * 1099511628211
    }
}

fn fnv_str_(h: *u64, const s: string) {
    var *p = s.as_ptr()
    for var i: usize = 0; i < s.length(); ++i {
        var x = *h
        *h = (x ^ (p[i] as u64)) * 1099511628211
    }
}

fn val_(b: u512) -> @F@ { return __builtin_bitcast<@F@, @STORE@>(b as @STORE@) }
fn enc_(x: @F@) -> u512 { return __builtin_bitcast<@STORE@, @F@>(x) as u512 }
fn cls_(x: @F@) -> @C@ { return @C@::from_bits(__builtin_bitcast<@STORE@, @F@>(x)) }

fn check_(const name: string, got: u64, want: u64) -> i32 {
    if got == want {
        io::println(f"{name} ok")
        return 0
    }
    io::println(f"{name} MISMATCH got {got} want {want}")
    return 1
}

fn main() -> i32 {
    var r = Rng { s: @SEED@ }
    var h: [u64; @NH@]
    for var i: i32 = 0; i < @NH@; ++i { h[i] = 14695981039346656037 }
    var trip_bad: i32 = 0
    for var i: i32 = 0; i < @N@; ++i {
        var a = gen_(&r, 0, false, false)
        var b = gen_(&r, a, true, false)
        var c = gen_(&r, 0, false, false)
        var x = val_(a)
        var y = val_(b)
        var z = val_(c)
        fnv_(&h[0], enc_(x + y), @NBYTES@)
        fnv_(&h[1], enc_(x - y), @NBYTES@)
        fnv_(&h[2], enc_(x * y), @NBYTES@)
        fnv_(&h[3], enc_(x / y), @NBYTES@)
        fnv_(&h[4], cls_(x).abs().sqrt().to_bits() as u512, @NBYTES@)
        fnv_(&h[5], cls_(x).fma(cls_(y), cls_(z)).to_bits() as u512, @NBYTES@)
        var cmp: u512 = 3
        if x < y { cmp = 1 } else if x == y { cmp = 0 } else if x > y { cmp = 2 }
        if (x <= y) != (cmp == 1 || cmp == 0) { cmp = 99 }
        if (x != y) == (cmp == 0) { cmp = 98 }
        fnv_(&h[6], cmp, 8)
        fnv_(&h[7], __builtin_bitcast<u64, f64>(x as f64) as u512, 8)
        fnv_(&h[8], __builtin_bitcast<u32, f32>(x as f32) as u512, 8)
        var d = next_(&r)
        fnv_(&h[9], enc_(__builtin_bitcast<f64, u64>(d) as @F@), @NBYTES@)
        fnv_(&h[10], (x as i64) as u64 as u512, 8)
        fnv_(&h[11], (x as u32) as u512, 8)
        fnv_(&h[12], (x as i512) as u512, 64)
        var si = next_(&r) as i64
        fnv_(&h[13], enc_(si as @F@), @NBYTES@)
        var wi = (bits_(&r, 300) as i512) - (bits_(&r, 299) as i512)
        fnv_(&h[14], enc_(wi as @F@), @NBYTES@)
@EXTRA_OPS@
    }
    for var i: i32 = 0; i < @NT@; ++i {
        var t = val_(gen_(&r, 0, false, true))
        var s1 = f"{t}"
        fnv_str_(&h[@HT0@], s1)
        fnv_str_(&h[@HT1@], f"{t:.20e}")
        fnv_str_(&h[@HT2@], f"{t:>12.5}")
        var back = @C@()
        if !@C@::parse(s1, &back) {
            trip_bad += 1
        } else if !cls_(t).is_nan() && back.to_bits() != cls_(t).to_bits() {
            trip_bad += 1
        }
    }
    var bad: i32 = 0
@CHECKS@
    if trip_bad == 0 { io::println("roundtrip ok") } else { io::println(f"roundtrip MISMATCH {trip_bad}") }
    return bad + trip_bad
}

// --- lit wiring -----------------------------------------------------------
// REQUIRES: clang
// RUN: rm -rf %t.d
// RUN: %kairo %s -o %t.exe --cache-dir %t.d
// RUN: %t.exe | %FileCheck %s
@CHECKLINES@
// CHECK: roundtrip ok
// CHECK-NOT: MISMATCH
'''

OPS = ['add', 'sub', 'mul', 'div', 'sqrt', 'fma', 'cmp', 'to_f64', 'to_f32', 'from_f64',
       'to_i64', 'to_u32', 'to_i512', 'from_i64', 'from_i512']


def build(n, oracle_dir, count, tcount, seed):
    sys.path.insert(0, oracle_dir)
    import wfo
    import textor
    f = wfo.Fmt(n, 19 if n == 256 else 23)
    f64, f32 = wfo.Fmt(64, 11), wfo.Fmt(32, 8)
    other = wfo.Fmt(512, 23) if n == 256 else wfo.Fmt(256, 19)
    nbytes = n // 8
    ops = list(OPS) + ['to_' + ('f512' if n == 256 else 'f256')]
    hs = {o: FNV0 for o in ops}
    r = Rng(seed)

    def sgn(x, w):
        x &= (1 << w) - 1
        return x - (1 << w) if x >> (w - 1) else x

    for i in range(count):
        a = gen(f, r)
        b = gen(f, r, near=a)
        c = gen(f, r)
        hs['add'] = fnv(hs['add'], wfo.add(f, a, b), nbytes)
        hs['sub'] = fnv(hs['sub'], wfo.add(f, a, b, True), nbytes)
        hs['mul'] = fnv(hs['mul'], wfo.mul(f, a, b), nbytes)
        hs['div'] = fnv(hs['div'], wfo.div(f, a, b), nbytes)
        hs['sqrt'] = fnv(hs['sqrt'], wfo.sqrt(f, a & ~(1 << (n - 1))), nbytes)
        hs['fma'] = fnv(hs['fma'], wfo.fma(f, a, b, c), nbytes)
        cm = wfo.cmp(f, a, b)
        hs['cmp'] = fnv(hs['cmp'], {0: 0, 1: 1, 2: 2, 3: 3}[cm], 8)
        hs['to_f64'] = fnv(hs['to_f64'], wfo.convert(f, f64, a), 8)
        hs['to_f32'] = fnv(hs['to_f32'], wfo.convert(f, f32, a), 8)
        d = r.next()
        hs['from_f64'] = fnv(hs['from_f64'], wfo.convert(f64, f, d), nbytes)
        hs['to_i64'] = fnv(hs['to_i64'], wfo.to_int(f, a, 64, True) & MASK64, 8)
        hs['to_u32'] = fnv(hs['to_u32'], wfo.to_int(f, a, 32, False), 8)
        hs['to_i512'] = fnv(hs['to_i512'], wfo.to_int(f, a, 512, True) & ((1 << 512) - 1), 64)
        si = sgn(r.next(), 64)
        hs['from_i64'] = fnv(hs['from_i64'], wfo.from_int(f, si), nbytes)
        wi = r.bits(300) - r.bits(299)
        hs['from_i512'] = fnv(hs['from_i512'], wfo.from_int(f, wi), nbytes)
        o = ops[-1]
        hs[o] = fnv(hs[o], wfo.convert(f, other, a), other.nbits // 8)
    th = [FNV0, FNV0, FNV0]
    for i in range(tcount):
        t = gen(f, r, moderate=True)
        neg = '-' if (t >> (n - 1)) & 1 else ''
        s1 = neg + textor.fmt(f, t, -1, 'g')
        s2 = neg + textor.fmt(f, t, 20, 'e')
        s3 = (neg + textor.fmt(f, t, 5, 'g')).rjust(12)
        th[0] = fnv_str(th[0], s1)
        th[1] = fnv_str(th[1], s2)
        th[2] = fnv_str(th[2], s3)
    return ops, hs, th


def render(n, ops, hs, th, count, tcount, seed):
    C = 'F256' if n == 256 else 'F512'
    other = 'f512' if n == 256 else 'f256'
    ocls = 'F512' if n == 256 else 'F256'
    ostore = 'u512' if n == 256 else 'u256'
    obytes = 64 if n == 256 else 32
    names = ops + ['text_shortest', 'text_e20', 'text_g5_width']
    nh = len(names)
    ht0 = len(ops)
    extra = f'        fnv_(&h[{len(ops) - 1}], __builtin_bitcast<{ostore}, {other}>(x as {other}) as u512, {obytes})'
    checks = []
    want = [hs[o] for o in ops] + th
    for i, nm in enumerate(names):
        checks.append(f'    bad += check_("{nm}", h[{i}], {want[i]})')
    s = TEMPLATE
    rep = {
        '@F@': f'f{n}', '@C@': C, '@N@': str(count), '@W@': str(n), '@M@': str(n - 1 - (19 if n == 256 else 23)),
        '@EMASK@': str((1 << (19 if n == 256 else 23)) - 1),
        '@BIAS@': str((1 << (18 if n == 256 else 22)) - 1), '@STORE@': f'u{n}',
        '@SEED@': str(seed), '@NH@': str(nh), '@NBYTES@': str(n // 8), '@NT@': str(tcount),
        '@HT0@': str(ht0), '@HT1@': str(ht0 + 1), '@HT2@': str(ht0 + 2),
        '@EXTRA_OPS@': extra, '@CHECKS@': '\n'.join(checks),
        '@CHECKLINES@': '\n'.join(f'// CHECK: {nm} ok' for nm in names),
    }
    for k, v in rep.items():
        s = s.replace(k, v)
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--oracle', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), 'softfloat_oracle'))
    ap.add_argument('--out', default=os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'Tests', 'Codegen'))
    ap.add_argument('--count', type=int, default=3000)
    ap.add_argument('--text', type=int, default=300)
    ap.add_argument('--width', type=int, choices=[256, 512], action='append')
    a = ap.parse_args()
    for n in (a.width or [256, 512]):
        seed = 0x9E3779B97F4A7C15 ^ n
        ops, hs, th = build(n, a.oracle, a.count, a.text, seed)
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        from gen_softfloat import kfmt
        text = kfmt(render(n, ops, hs, th, a.count, a.text, seed), f'f{n}_ops.k')
        open(os.path.join(a.out, f'f{n}_ops.k'), 'w').write(text)


if __name__ == '__main__':
    main()
