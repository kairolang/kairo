#!/usr/bin/env python3
"""Generate Compiler/Lexer/UnicodeTables.k from the Unicode Character Database.

The lexer classifies a non-ASCII character by three properties:

    XID_Start      may start an identifier         (UAX #31)
    XID_Continue   may continue an identifier      (UAX #31)
    White_Space    separates tokens

Each becomes a table of inclusive [first, last] code point ranges, ascending
and non-adjacent, which the lexer searches by bisection. ASCII is left out:
the lexer's 128-entry table owns it and never reaches these.

The inputs are two files of one UCD release:

    DerivedCoreProperties.txt   XID_Start, XID_Continue
    PropList.txt                White_Space

from https://www.unicode.org/Public/<version>/ucd/. Nothing is downloaded
here and nothing runs at build time: the generated file is checked in.

    python3 Scripts/gen_unicode_tables.py --ucd <dir>            # rewrite
    python3 Scripts/gen_unicode_tables.py --ucd <dir> --check    # compare only

To move to a new Unicode version, fetch its two files into a directory and
run the first form; the version is read from the files' first lines.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = ROOT / "Compiler" / "Lexer" / "UnicodeTables.k"

LINE = re.compile(r"^([0-9A-Fa-f]{4,6})(?:\.\.([0-9A-Fa-f]{4,6}))?\s*;\s*(\w+)")
VERSION = re.compile(r"^# \w+-(\d+\.\d+\.\d+)\.txt")

PAIRS_PER_LINE = 4


def read_properties(path, wanted):
    """The ranges of each property in `wanted`, and the file's UCD version."""
    ranges = {name: [] for name in wanted}
    version = None
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f):
            if n == 0:
                m = VERSION.match(line)
                if m:
                    version = m.group(1)

            m = LINE.match(line)
            if m is None or m.group(3) not in ranges:
                continue

            first = int(m.group(1), 16)
            last = int(m.group(2), 16) if m.group(2) else first
            ranges[m.group(3)].append((first, last))

    if version is None:
        sys.exit(f"{path}: no '# <Name>-<version>.txt' line; is this a UCD file?")

    for name, rs in ranges.items():
        if not rs:
            sys.exit(f"{path}: no {name} entries")

    return ranges, version


def non_ascii_merged(ranges):
    """Sorted, with ASCII cut off and touching ranges joined."""
    out = []
    for first, last in sorted(ranges):
        if last < 0x80:
            continue

        first = max(first, 0x80)
        if out and first <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], last))
        else:
            out.append((first, last))

    return out


def table(name, doc, ranges):
    lines = [f"    /// {d}" for d in doc]
    lines.append(f"    pub eval {name}: [u32; {len(ranges) * 2}] = [")
    for i in range(0, len(ranges), PAIRS_PER_LINE):
        row = ranges[i:i + PAIRS_PER_LINE]
        lines.append("        " + " ".join(f"0x{a:06X}, 0x{b:06X}," for a, b in row))

    lines.append("    ]")
    return "\n".join(lines)


def render(xid_start, xid_continue, white_space, version):
    head = f"""/// --- The Kairo Project ------------------------ Lexer/UnicodeTables.k --- ///
///
///   The Unicode properties the lexer reads for a non-ASCII character, as
///   tables of inclusive [first, last] code point ranges: ascending, never
///   touching, searched by bisection (Lexer::in_ranges). ASCII is not in
///   them; the lexer's 128-entry table owns it.
///
///   Unicode {version}. GENERATED by Scripts/gen_unicode_tables.py from
///   DerivedCoreProperties.txt and PropList.txt of that release: regenerate,
///   do not edit.
///
///   Part of the Kairo Project, under the Apache License v2.0 with the
///   Kairo Runtime Library Exception.
///
///   See: https://www.kairolang.org/LICENSE
///   SPDX-License-Identifier: Apache-2.0 WITH AdditionRef-Kairo-Runtime-exception
///   Copyright (c) 2026 Dhruvan Kartik
///
/// ------------------------------------------------------------------------ ///

pub module UnicodeTables {{
"""
    body = "\n\n".join([
        table(
            "XID_START",
            [f"XID_Start (UAX #31): the characters that may start an identifier. {len(xid_start)} ranges."],
            xid_start,
        ),
        table(
            "XID_CONTINUE",
            [
                "XID_Continue (UAX #31): the characters that may follow the first; a",
                f"superset of XID_START. {len(xid_continue)} ranges.",
            ],
            xid_continue,
        ),
        table(
            "WHITE_SPACE",
            [f"White_Space: the characters that separate tokens. {len(white_space)} ranges."],
            white_space,
        ),
    ])

    return head + body + "\n}\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--ucd", required=True, type=Path,
                    help="directory holding DerivedCoreProperties.txt and PropList.txt")
    ap.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 when the output file differs; write nothing")
    args = ap.parse_args()

    core, v_core = read_properties(args.ucd / "DerivedCoreProperties.txt",
                                   ["XID_Start", "XID_Continue"])
    prop, v_prop = read_properties(args.ucd / "PropList.txt", ["White_Space"])
    if v_core != v_prop:
        sys.exit(f"the two files are of different Unicode versions: {v_core} and {v_prop}")

    xid_start = non_ascii_merged(core["XID_Start"])
    xid_continue = non_ascii_merged(core["XID_Continue"])
    white_space = non_ascii_merged(prop["White_Space"])

    text = render(xid_start, xid_continue, white_space, v_core)
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != text:
            print(f"{args.output}: differs from the tables of Unicode {v_core}")
            return 1

        return 0

    args.output.write_text(text, encoding="utf-8")
    print(f"{args.output}: Unicode {v_core}, {len(xid_start)} XID_Start, "
          f"{len(xid_continue)} XID_Continue, {len(white_space)} White_Space ranges")
    return 0


if __name__ == "__main__":
    sys.exit(main())
