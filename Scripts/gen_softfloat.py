"""Generates the mechanical parts of Kairo's software floats.

  Lib/builtin/num/f256_t.k, f512_t.k  the two classes, from one template
                                      (they differ only in width, exponent
                                      width and storage integer);
  Lib/builtin/num/softfloat_text.k    the SfB limb primitives between its
                                      BEGIN/END-GENERATED(sfb) markers: a
                                      copy of softfloat.k's sfw_* at SfB's
                                      width.

usage: python3 Scripts/gen_softfloat.py [--check]
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NUM = os.path.join(ROOT, 'Lib', 'builtin', 'num')

TEMPLATE = r'''/// --- The Kairo Project ----------------------- Lib/builtin/num/@F@_t.k --- ///
///
///   \brief `@F@`, IEEE 754 @IEEE@, as a library class: the C++ spelling
///          of the `@F@` type keyword (AST/Node/CanonicalNodes.k).
///
///   \detail
///     @LAYOUT@
///
///     No LLVM type exists at this width, so every operation is a call into
///     num/softfloat.k (arithmetic, conversions) and num/softfloat_text.k
///     (decimal text), the same engine at every width. Correctly rounded
///     (to nearest, ties to even) everywhere, signed zeros, subnormals,
///     infinities; a NaN result is the canonical quiet NaN. Sema types the
///     operators and casts on `@F@` as it does any float's; the C++ they
///     lower to (`a + b`, `static_cast<double>(x)`) lands on the members
///     here.
///
///     A float-to-integer cast truncates toward zero and saturates at the
///     target's limits, NaN giving 0 (casting.mdx). Generated by
///     Scripts/gen_softfloat.py from one template with
///     @OTHER@_t.k; change both. The file is not `@F@.k` because `@F@` is
///     a keyword, and a keyword cannot be a module path segment.
///
///   SPDX-License-Identifier: Apache-2.0 WITH AdditionRef-Kairo-Runtime-exception
///   Copyright (c) 2026 Dhruvan Kartik
///
/// ------------------------------------------------------------------------ ///

import num::softfloat::*
import num::softfloat_text::*
@IMPORTS@import base::intrinsics::*
import base::c_char::*
import string::*

/// The `@F@` type: @IEEE@ in a @STORE@ (bit @TOPBIT@ the sign).
///
/// Aligned to its size, as Kairo lays out @STORE@ (clang's _BitInt is only
/// 8-aligned; without the attribute the two layouts of `@F@?` differ, P720).
@align(@ALIGN@)
pub class @C@ {
    /// The encoding.
    pub var bits: @STORE@ = 0

    /// +0.0.
    pub fn @C@(self) { self.bits = 0 }

    /// The encoding's format for the engine.
    pub inline static fn fmt_() -> SfFmt { return sf_fmt(@N@, @E@) }

    /// The value whose encoding is `b`.
    pub inline static fn from_bits(b: @STORE@) -> @C@ {
        var r = @C@()
        r.bits = b
        return r
    }

    /// The encoding.
    pub inline fn to_bits(const self) -> @STORE@ { return self.bits }

    // --- from other types: what `x as @F@` lowers to ---------------------

    /// `x as @F@` from f64, exactly (every f64 is an @F@).
    pub fn @C@(self, v: f64) {
        self.bits = sf_cvt(@C@::fmt_(), sf_fmt(64, 11), __builtin_bitcast<u64, f64>(v) as u512)@TOSTORE@
    }

    /// `x as @F@` from f32.
    pub fn @C@(self, v: f32) {
        self.bits = sf_cvt(@C@::fmt_(), sf_fmt(32, 8), __builtin_bitcast<u32, f32>(v) as u512)@TOSTORE@
    }

@FROM_INTS@
@FROM_OTHER@
    // clang defines __FLT16_MAX__ exactly where _Float16 exists (fmt_buf.k).
    eval if defined!(__FLT16_MAX__) {
        /// `x as @F@` from f16.
        pub fn @C@(self, v: f16) {
            self.bits = sf_cvt(@C@::fmt_(), sf_fmt(16, 5), __builtin_bitcast<u16, f16>(v) as u512)@TOSTORE@
        }

        /// `x as f16`, rounded once.
        pub fn op as (const self) -> f16 {
            return __builtin_bitcast<f16, u16>(sf_cvt(sf_fmt(16, 5), @C@::fmt_(), self.bits@ASW@) as u16)
        }
    }

    // The arches clang gives __bf16 (fmt_buf.k says why there is no macro),
    // but wasm: there a bf16 value's mere passing calls compiler-rt's
    // __truncsfbf2 with the wrong signature (P706), a link warning in every
    // program.
    eval if defined!(__x86_64__) || defined!(__i386__) || defined!(__aarch64__) || defined!(__arm__)
         || defined!(__riscv) || defined!(__loongarch__) {
        /// `x as @F@` from bf16.
        pub fn @C@(self, v: bf16) {
            self.bits = sf_cvt(@C@::fmt_(), sf_fmt(16, 8), __builtin_bitcast<u16, bf16>(v) as u512)@TOSTORE@
        }

        /// `x as bf16`, rounded once.
        pub fn op as (const self) -> bf16 {
            return __builtin_bitcast<bf16, u16>(sf_cvt(sf_fmt(16, 8), @C@::fmt_(), self.bits@ASW@) as u16)
        }
    }

    // __SIZEOF_FLOAT128__ marks __float128; wasm32 has it without the macro.
    eval if defined!(__SIZEOF_FLOAT128__) || defined!(__wasm__) {
        /// `x as @F@` from f128.
        pub fn @C@(self, v: f128) {
            self.bits = sf_cvt(@C@::fmt_(), sf_fmt(128, 15), __builtin_bitcast<u128, f128>(v) as u512)@TOSTORE@
        }

        /// `x as f128`, rounded once.
        pub fn op as (const self) -> f128 {
            return __builtin_bitcast<f128, u128>(sf_cvt(sf_fmt(128, 15), @C@::fmt_(), self.bits@ASW@) as u128)
        }
    }

    // f80 is x87 extended where it exists at all (fmt_buf.k's gate). Its
    // bytes are read and written directly: sizeof is 16 or 12, the value
    // is the low 10, little-endian (x86).
    eval if (defined!(__x86_64__) || defined!(__i386__)) && !defined!(_MSC_VER) && !defined!(__ANDROID__) {
        /// `x as @F@` from f80.
        pub fn @C@(self, v: f80) {
            var m: u64 = 0
            var se: u16 = 0
            unsafe {
                var unsafe *p = (&v) as unsafe *const u8
                for var i: i32 = 7; i >= 0; i -= 1 { m = (m << 8) | (p[i] as u64) }
                se = (p[8] as u16) | ((p[9] as u16) << 8)
            }
            self.bits = sf_cvt(@C@::fmt_(), sf_fmt(79, 15), sf_from_x87(se, m))@TOSTORE@
        }

        /// `x as f80`, rounded once.
        pub fn op as (const self) -> f80 {
            var se: u16 = 0
            var m: u64 = 0
            sf_to_x87(sf_cvt(sf_fmt(79, 15), @C@::fmt_(), self.bits@ASW@), &se, &m)
            var r: f80 = 0.0
            unsafe {
                var unsafe *p = (&r) as unsafe *u8
                for var i: i32 = 0; i < 8; ++i { p[i] = (m >> ((8 * i) as u64)) as u8 }
                p[8] = se as u8
                p[9] = (se >> 8) as u8
            }
            return r
        }
    }

    // --- to other types: what `x as T` lowers to ---------------------------

    /// `x as f64`, rounded once (never through an intermediate format).
    pub fn op as (const self) -> f64 {
        return __builtin_bitcast<f64, u64>(sf_cvt(sf_fmt(64, 11), @C@::fmt_(), self.bits@ASW@) as u64)
    }

    /// `x as f32`, rounded once.
    pub fn op as (const self) -> f32 {
        return __builtin_bitcast<f32, u32>(sf_cvt(sf_fmt(32, 8), @C@::fmt_(), self.bits@ASW@) as u32)
    }

@TO_INTS@
    // --- text ----------------------------------------------------------------

    /// The correctly rounded value of a decimal or hex float literal's
    /// digits: what the compiler emits for `1.5@F@`, `0.1` typed `@F@`, and
    /// so on (EmitIR's float literal). Not for users: `parse` is.
    pub static fn lit_(p: *const __builtin_c_char, n: usize) -> @C@ {
        var r = @C@()
        var v: u512 = 0
        unsafe { sf_parse_bits(@C@::fmt_(), p as unsafe *const u8 as *const u8, n, &v) }
        r.bits = v@TOSTORE@
        return r
    }

    /// Parses `s` (decimal, `0x` hex, `inf`, `infinity`, `nan`, an optional
    /// sign, `_` between digits), correctly rounded, into `*out`; false
    /// (out untouched) when `s` is not a float.
    ///
    /// \note Not `-> @C@?`: a nullable return from a builtin class with
    /// this alignment does not compile yet (P721).
    pub static fn parse(const s: string, out: *@C@) -> bool {
        var v: u512 = 0
        if !sf_parse_bits(@C@::fmt_(), s.as_ptr(), s.length(), &v) { return false }
        out->bits = v@TOSTORE@
        return true
    }

    /// |self| as text into out[0..cap) (rt/fmt.h's contract: conv 'g',
    /// 'e' or 'E', prec < 0 for the shortest round-trip digits); returns the
    /// bytes written. The sign is the caller's (FmtBuf::put_@F@).
    pub fn format_into_(const self, out: unsafe *u8, cap: usize, prec: i32, conv: u8) -> i32 {
        return sf_format_bits(@C@::fmt_(), self.bits@ASW@, out, cap, prec, conv)
    }

    // --- arithmetic ---------------------------------------------------------

    /// self + o, rounded to nearest even.
    pub fn op + (const self, const o: @C@) -> @C@ { return @C@::from_bits(sf_op(@C@::fmt_(), SF_OP_ADD, self.bits@ASW@, o.bits@ASW@, 0)@TOSTORE@) }
    /// self - o, rounded to nearest even.
    pub fn op - (const self, const o: @C@) -> @C@ { return @C@::from_bits(sf_op(@C@::fmt_(), SF_OP_SUB, self.bits@ASW@, o.bits@ASW@, 0)@TOSTORE@) }
    /// self * o, rounded to nearest even.
    pub fn op * (const self, const o: @C@) -> @C@ { return @C@::from_bits(sf_op(@C@::fmt_(), SF_OP_MUL, self.bits@ASW@, o.bits@ASW@, 0)@TOSTORE@) }
    /// self / o, rounded to nearest even.
    pub fn op / (const self, const o: @C@) -> @C@ { return @C@::from_bits(sf_op(@C@::fmt_(), SF_OP_DIV, self.bits@ASW@, o.bits@ASW@, 0)@TOSTORE@) }

    /// -self: the sign bit flipped (NaN included).
    pub fn op - (const self) -> @C@ { return @C@::from_bits(self.bits ^ ((1 as @STORE@) << @TOPBIT@)) }

    // `+=` and the rest derive from these (operator-overloading.mdx).

    /// The square root, correctly rounded; sqrt(-0) is -0, other negatives NaN.
    pub fn sqrt(const self) -> @C@ { return @C@::from_bits(sf_op(@C@::fmt_(), SF_OP_SQRT, self.bits@ASW@, 0, 0)@TOSTORE@) }

    /// self * b + c, rounded once.
    pub fn fma(const self, const b: @C@, const c: @C@) -> @C@ {
        return @C@::from_bits(sf_op(@C@::fmt_(), SF_OP_FMA, self.bits@ASW@, b.bits@ASW@, c.bits@ASW@)@TOSTORE@)
    }

    /// |self|: the sign bit cleared.
    pub fn abs(const self) -> @C@ { return @C@::from_bits(self.bits & ~((1 as @STORE@) << @TOPBIT@)) }

    /// self's magnitude with s's sign.
    pub fn copysign(const self, const s: @C@) -> @C@ {
        var m: @STORE@ = (1 as @STORE@) << @TOPBIT@
        return @C@::from_bits((self.bits & ~m) | (s.bits & m))
    }

    // --- comparison: IEEE, a NaN is unordered with everything ---------------

    /// IEEE equality: false when either is NaN; -0 == +0.
    pub fn op == (const self, const o: @C@) -> bool { return sf_cmp_bits(@C@::fmt_(), self.bits@ASW@, o.bits@ASW@) == 0 }
    /// The negation of ==: true when either is NaN.
    pub fn op != (const self, const o: @C@) -> bool { return sf_cmp_bits(@C@::fmt_(), self.bits@ASW@, o.bits@ASW@) != 0 }
    /// IEEE less-than: false when unordered.
    pub fn op < (const self, const o: @C@) -> bool { return sf_cmp_bits(@C@::fmt_(), self.bits@ASW@, o.bits@ASW@) == -1 }
    /// IEEE less-or-equal: false when unordered.
    pub fn op <= (const self, const o: @C@) -> bool {
        var c = sf_cmp_bits(@C@::fmt_(), self.bits@ASW@, o.bits@ASW@)
        return c == -1 || c == 0
    }
    /// IEEE greater-than: false when unordered.
    pub fn op > (const self, const o: @C@) -> bool { return sf_cmp_bits(@C@::fmt_(), self.bits@ASW@, o.bits@ASW@) == 1 }
    /// IEEE greater-or-equal: false when unordered.
    pub fn op >= (const self, const o: @C@) -> bool {
        var c = sf_cmp_bits(@C@::fmt_(), self.bits@ASW@, o.bits@ASW@)
        return c == 1 || c == 0
    }

    /// Whether either is a NaN (IEEE's unordered predicate).
    pub fn is_unordered(const self, const o: @C@) -> bool { return sf_cmp_bits(@C@::fmt_(), self.bits@ASW@, o.bits@ASW@) == 2 }

    // --- classification -----------------------------------------------------

    /// Whether self is a NaN.
    pub fn is_nan(const self) -> bool { return sf_class_bits(@C@::fmt_(), self.bits@ASW@) == SF_NAN }
    /// Whether self is an infinity.
    pub fn is_infinite(const self) -> bool { return sf_class_bits(@C@::fmt_(), self.bits@ASW@) == SF_INF }
    /// Whether self is neither infinite nor NaN.
    pub fn is_finite(const self) -> bool { return sf_class_bits(@C@::fmt_(), self.bits@ASW@) < SF_INF }
    /// Whether self is +0 or -0.
    pub fn is_zero(const self) -> bool { return sf_class_bits(@C@::fmt_(), self.bits@ASW@) == SF_ZERO }
    /// Whether self is subnormal (nonzero, below the smallest normal).
    pub fn is_subnormal(const self) -> bool { return sf_subnormal_bits(@C@::fmt_(), self.bits@ASW@) }
    /// Whether self is normal (finite, nonzero, not subnormal).
    pub fn is_normal(const self) -> bool { return sf_class_bits(@C@::fmt_(), self.bits@ASW@) == SF_FINITE && !self.is_subnormal() }
    /// Whether the sign bit is set (-0.0 and negative NaNs included).
    pub fn is_sign_negative(const self) -> bool { return (self.bits >> @TOPBIT@) != 0 }

    // --- limits ---------------------------------------------------------------

    /// +infinity.
    pub static fn infinity() -> @C@ { return @C@::from_bits(@C@::exp_mask_()) }
    /// -infinity.
    pub static fn neg_infinity() -> @C@ { return @C@::from_bits(@C@::exp_mask_() | ((1 as @STORE@) << @TOPBIT@)) }
    /// The canonical quiet NaN.
    pub static fn nan() -> @C@ { return @C@::from_bits(@C@::exp_mask_() | ((1 as @STORE@) << @QBIT@)) }
    /// The largest finite value.
    pub static fn max() -> @C@ { return @C@::from_bits(@C@::exp_mask_() - 1) }
    /// The smallest positive normal value.
    pub static fn min_positive() -> @C@ { return @C@::from_bits((1 as @STORE@) << @M@) }
    /// The smallest positive subnormal value.
    pub static fn min_subnormal() -> @C@ { return @C@::from_bits(1) }
    /// The gap between 1.0 and the next value up: 2^-@M@.
    pub static fn epsilon() -> @C@ { return @C@::from_bits(((@BIAS@ - @M@) as @STORE@) << @M@) }

    priv inline static fn exp_mask_() -> @STORE@ { return (((1 as @STORE@) << @E@) - 1) << @M@ }
}
'''

# isize / usize are ptrdiff_t / size_t: the same C++ type as i64 / u64 (or
# i32 / u32) on most targets, where a second constructor would collide
# (R052E), and a distinct one on 64-bit Apple (long vs long long) and wasm32
# (long vs int). They get their own overloads only there (SIZE_OVERLOADS).
INTS = ['i8', 'i16', 'i32', 'i64', 'u8', 'u16', 'u32', 'u64',
        'i128', 'u128', 'i256', 'u256', 'i512', 'u512']
WIDTH = {'i8': 8, 'i16': 16, 'i32': 32, 'i64': 64, 'u8': 8, 'u16': 16, 'u32': 32, 'u64': 64,
         'i128': 128, 'u128': 128, 'i256': 256, 'u256': 256, 'i512': 512, 'u512': 512}


def from_ints(C, F, STORE):
    out = []
    for t in INTS:
        signed = t.startswith('i')
        if signed:
            mag = f'(if v < 0 => (0 as u512) - (v as u512) else => v as u512)'
            neg = 'v < 0'
        else:
            mag = 'v' if t == 'u512' else 'v as u512'
            neg = 'false'
        to = '' if STORE == 'u512' else f' as {STORE}'
        out.append(f'''    /// `x as {F}` from {t}, rounded to nearest even.
    pub fn {C}(self, v: {t}) {{
        var mag: u512 = {mag}
        self.bits = sf_from_mag({C}::fmt_(), mag, {neg}){to}
    }}
''')
    return '\n'.join(out)


def to_ints(C, F, STORE):
    out = []
    for t in INTS:
        signed = 'true' if t.startswith('i') else 'false'
        w = str(WIDTH[t])
        asw = '' if STORE == 'u512' else ' as u512'
        cast = '' if t == 'u512' else f' as {t}'
        out.append(f'''    /// `x as {t}`: toward zero, saturating, NaN 0.
    pub fn op as (const self) -> {t} {{ return sf_to_sat({C}::fmt_(), self.bits{asw}, {w}, {signed}){cast} }}
''')
    return '\n'.join(out)


def size_overloads(C, F, STORE):
    body = []
    for t, signed in (('isize', 'true'), ('usize', 'false')):
        if signed == 'true':
            mag = '(if v < 0 => (0 as u512) - (v as u512) else => v as u512)'
            neg = 'v < 0'
        else:
            mag = 'v as u512'
            neg = 'false'
        body.append(f'''        /// `x as {F}` from {t}.
        pub fn {C}(self, v: {t}) {{
            var mag: u512 = {mag}
            self.bits = sf_from_mag({C}::fmt_(), mag, {neg}){'' if STORE == 'u512' else ' as ' + STORE}
        }}

        /// `x as {t}`: toward zero, saturating, NaN 0.
        pub fn op as (const self) -> {t} {{ return sf_to_sat({C}::fmt_(), self.bits{'' if STORE == 'u512' else ' as u512'}, W, {signed}) as {t} }}
''')
    b = '\n'.join(body)
    return ('''    // isize / usize where they are not i64 / u64 or i32 / u32 under another
    // name (elsewhere those overloads already take them).
    eval if defined!(__APPLE__) && defined!(__LP64__) {
''' + b.replace('W,', '64,') + '''    }

    eval if defined!(__wasm32__) {
''' + b.replace('W,', '32,') + '''    }
''')


def gen(n):
    if n == 256:
        p = dict(ALIGN=32, F='f256', C='F256', N=256, E=19, M=236, BIAS=262143, STORE='u256', TOPBIT=255, QBIT=235,
                 OTHER='f512', IEEE='binary256',
                 LAYOUT='Sign, 19-bit exponent (bias 262143), 236-bit fraction with a\n///     hidden leading bit: 237 bits of precision, 71 decimal digits, range\n///     about 10^+-78913. The interchange format IEEE 754-2019 3.6 defines\n///     for k = 256.',
                 IMPORTS='')
        p['FROM_OTHER'] = ''
    else:
        p = dict(ALIGN=64, F='f512', C='F512', N=512, E=23, M=488, BIAS=4194303, STORE='u512', TOPBIT=511, QBIT=487,
                 OTHER='f256', IEEE='"binary512"',
                 LAYOUT='Sign, 23-bit exponent (bias 4194303), 488-bit fraction with a\n///     hidden leading bit: 489 bits of precision, 147 decimal digits, range\n///     about 10^+-1262612. IEEE 754 defines no 512-bit format; this is its\n///     interchange-format rule (3.6, Table 3.5) carried to k = 512:\n///     precision p = k - round(4 log2(k)) + 13 = 489, so the exponent is\n///     w = k - p = round(4 * 9) - 13 = 23 bits and emax = 2^22 - 1. The\n///     rule gives 15 at k = 128 and 19 at k = 256, the standard widths.',
                 IMPORTS='import num::f256_t::*\n')
        p['FROM_OTHER'] = '''    /// `x as f512` from f256, exactly.
    pub fn F512(self, const v: F256) {
        self.bits = sf_cvt(F512::fmt_(), F256::fmt_(), v.bits as u512)
    }

    /// `x as f256`, rounded once.
    pub fn op as (const self) -> F256 {
        return F256::from_bits(sf_cvt(F256::fmt_(), F512::fmt_(), self.bits) as u256)
    }
'''
    s = TEMPLATE
    s = s.replace('@FROM_INTS@', from_ints(p['C'], p['F'], p['STORE']))
    s = s.replace('@TO_INTS@', to_ints(p['C'], p['F'], p['STORE']) + '\n' + size_overloads(p['C'], p['F'], p['STORE']))
    s = s.replace('@FROM_OTHER@', p.pop('FROM_OTHER'))
    s = s.replace('@ASW@', '' if n == 512 else ' as u512').replace('@TOSTORE@', '' if n == 512 else ' as u256')
    for k, v in p.items():
        s = s.replace('@' + k + '@', str(v))
    return s


def sfb_block():
    src = open(os.path.join(NUM, 'softfloat.k')).read()
    start = src.index('/// Zeroes limbs [0, n).')
    end = src.index('/// floor(sqrt(a)) into r')
    body = src[start:end].rstrip() + '\n'
    # sf_clz32 is width-free: the copy calls softfloat.k's.
    i = body.index('pub fn sf_clz32(')
    j = body.index('\n}\n', i) + 3
    body = body[:i] + body[j:].lstrip('\n')
    return body.replace('SfW', 'SfB').replace('sfw_', 'sfb_')


def splice(text, block):
    b = '// BEGIN-GENERATED(sfb)\n'
    e = '// END-GENERATED(sfb)\n'
    i = text.index(b) + len(b)
    j = text.index(e)
    return text[:i] + block + text[j:]


def kfmt_path():
    import shutil
    import glob
    for c in glob.glob(os.path.join(ROOT, 'build', '*', 'debug', 'bin', 'kfmt')):
        return c
    return shutil.which('kfmt')


def kfmt(text, name):
    """text as kfmt formats it (the repo's style), or unchanged when there is
    no kfmt to ask."""
    import subprocess
    import tempfile
    k = kfmt_path()
    if k is None:
        return text
    with tempfile.TemporaryDirectory() as d:
        p = os.path.join(d, name)
        open(p, 'w').write(text)
        r = subprocess.run([k, '--stdout', '--normalize-parens', '--call-width=100', p],
                           capture_output=True, text=True)
        return r.stdout if r.returncode == 0 and r.stdout else text


def main():
    check = '--check' in sys.argv
    outs = {}
    for n in (256, 512):
        outs[os.path.join(NUM, f'f{n}_t.k')] = gen(n)
    tp = os.path.join(NUM, 'softfloat_text.k')
    outs[tp] = splice(open(tp).read(), sfb_block())
    outs = {p: kfmt(s, os.path.basename(p)) for p, s in outs.items()}
    stale = []
    for p, s in outs.items():
        old = open(p).read() if os.path.exists(p) else None
        if old != s:
            stale.append(p)
            if not check:
                open(p, 'w').write(s)
    if check and stale:
        print('stale:', *stale)
        sys.exit(1)


if __name__ == '__main__':
    main()
