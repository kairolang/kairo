#!/usr/bin/env python3
"""Interim library-docs extractor for the Kairo website.

INTERIM: this is a text-level extractor that stands in until a compiler-driven
docgen (reading the real AST/Sema) exists. It does not parse Kairo; it lexes
just enough (comments, strings, braces, parens, declaration keywords) to find
every `pub` declaration, its `///` comment block and its signature. Where the
two disagree the compiler is right and this script has a bug. It reads the
doc-comment format in build/libdocs/STYLE.md (tags \\param \\returns \\panics
\\safety \\example \\note \\see; legacy \\brief/\\detail/\\par/\\class are
tolerated) and writes one MDX page per module/area into the website.

Usage:
    python3 Scripts/gen_lib_docs.py [--lib Lib] [--web <kairo-web checkout>]
                                    [--allow-undocumented]

`--lib` is a directory holding `builtin/` (core, the implicit prelude) and
`std/`. Output: <web>/src/content/docs/library/{index,core/*,std/*}.mdx.

Deterministic: same input gives byte-identical output (no timestamps, sorted
traversal). Exit status is 1 when a `pub` declaration has no doc comment,
unless --allow-undocumented (then it is a warning). Per-file counts are printed.

Rules beyond the style guide:
  * a member written on the same line as its `extend`/`class` header cannot
    carry its own `///`; it inherits the nearest `///` block above an extend in
    the same run of consecutive extends, else the doc of the interface method
    it implements. Members of `extend T impl I` are never "undocumented".
  * `extend <primitive> impl I` blocks (3 or more for one `I`) are rendered as
    one table instead of one section each.
  * enum cases on the same line as the enum header are part of its signature.
  * a few `priv` items users meet through syntax (INCLUDE_PRIVATE) are shown.
"""
