# ---------------------------------------------------------------------- lexing


class Tok:
    __slots__ = ("kind", "text", "start", "end", "line", "eline")

    def __init__(self, kind, text, start, end, line, eline):
        self.kind, self.text, self.start, self.end = kind, text, start, end
        self.line, self.eline = line, eline


IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
NUMBER = re.compile(r"[0-9][0-9A-Za-z_.]*")
CHARLIT = re.compile(r"'(\\.[0-9a-fA-F]*|[^'\\\n])'")


def lex(src):
    """Tokens (comments dropped, string contents opaque) plus `///` blocks keyed by end line."""
    toks, docs = [], {}
    i, n, line = 0, len(src), 1
    cur = None  # [lines, end_line]
    line_start = True
    while i < n:
        c = src[i]
        if c == "\n":
            line += 1
            i += 1
            line_start = True
            continue
        if c in " \t\r":
            i += 1
            continue
        if line_start and src.startswith("///", i) and not src.startswith("////", i):
            j = src.find("\n", i)
            j = n if j < 0 else j
            text = src[i + 3:j]
            if cur is not None and cur[1] == line - 1:
                cur[0].append(text)
                cur[1] = line
            else:
                if cur is not None:
                    docs[cur[1]] = cur[0]
                cur = [[text], line]
            i = j
            continue
        line_start = False
        if src.startswith("//", i):
            j = src.find("\n", i)
            i = n if j < 0 else j
            continue
        if src.startswith("/*", i):
            j = src.find("*/", i + 2)
            j = n if j < 0 else j + 2
            line += src.count("\n", i, j)
            i = j
            continue
        if c == '"' or (c in "fbr" and src.startswith('"', i + 1) and
                        (i == 0 or not (src[i - 1].isalnum() or src[i - 1] == "_"))):
            s = i
            sl = line
            i = i + 1 if c == '"' else i + 2
            while i < n and src[i] != '"':
                if src[i] == "\\":
                    i += 1
                if i < n and src[i] == "\n":
                    line += 1
                i += 1
            i += 1
            toks.append(Tok("str", "", s, i, sl, line))
            continue
        if c == "'":
            m = CHARLIT.match(src, i)
            if m:
                toks.append(Tok("str", "", i, m.end(), line, line))
                i = m.end()
                continue
        if c.isalpha() or c == "_":
            m = IDENT.match(src, i)
            t = m.group(0)
            e = m.end()
            if e < n and src[e] == "!" and not src.startswith("!=", e):
                t += "!"
                e += 1
            toks.append(Tok("id", t, i, e, line, line))
            i = e
            continue
        if c.isdigit():
            m = NUMBER.match(src, i)
            t = m.group(0)
            if ".." in t:
                t = t[:t.index("..")]
            toks.append(Tok("num", t, i, i + len(t), line, line))
            i += len(t)
            continue
        for p in PUNCT:
            if src.startswith(p, i):
                toks.append(Tok("p", p, i, i + len(p), line, line))
                i += len(p)
                break
        else:
            toks.append(Tok("p", c, i, i + 1, line, line))
            i += 1
    if cur is not None:
        docs[cur[1]] = cur[0]
    return toks, docs


def join_toks(toks, src):
    """Source text of a token run: comments dropped, whitespace normalized."""
    out = []
    prev = None
    for t in toks:
        txt = re.sub(r"\s+", " ", src[t.start:t.end]) if t.kind == "str" else t.text
        if prev is not None:
            if t.line != prev.eline:
                sep = "" if (prev.text in ("(", "[") or t.text in (")", "]", ",")) else " "
            else:
                sep = " " if t.start > prev.end else ""
            out.append(sep)
        out.append(txt)
        prev = t
    return re.sub(r",\s*([)\]])", r"\1", "".join(out))


# --------------------------------------------------------------------- items


class Item:
    def __init__(self):
        self.kind = ""
        self.name = ""
        self.sig = ""
        self.attrs = []
        self.doc = None
        self.pub = False
        self.line = 0
        self.children = []
        self.parent = None
        self.file = ""
        self.one_liner = False
        self.inherited = False
        self.impl = ""
        self.target = ""
        self.section = ""
        self.imported = []


class Parser:
    def __init__(self, src, rel):
        self.src = src
        self.rel = rel
        self.toks, self.docs = lex(src)
        self.items = []
        self.banner = None

    def doc_before(self, tok):
        return self.docs.get(tok.line - 1)

    def skip_braces(self, i):
        d, n = 0, len(self.toks)
        while i < n:
            t = self.toks[i]
            if t.kind == "p":
                if t.text == "{":
                    d += 1
                elif t.text == "}":
                    d -= 1
                    if d == 0:
                        return i + 1
            i += 1
        return n

    def skip_expr(self, start, enum_ctx):
        """Skip a `= expr` tail; stops before the next declaration or the container's `}`."""
        toks, n, d = self.toks, len(self.toks), 0
        i = start
        while i < n:
            t = toks[i]
            if t.kind == "p":
                if t.text in ("(", "[", "{"):
                    d += 1
                elif t.text in (")", "]", "}"):
                    if d == 0:
                        return i
                    d -= 1
                elif d == 0 and t.text == ";":
                    return i + 1
                elif d == 0 and t.text == "," and enum_ctx:
                    return i + 1
            if d == 0 and i > start and t.line != toks[i - 1].eline:
                if enum_ctx or (t.kind in ("id", "p") and t.text in STARTERS):
                    return i
            i += 1
        return n

    def parse(self):
        for _, lines in sorted(self.docs.items()):
            if lines and lines[0].strip().startswith("--- The Kairo Project"):
                self.banner = lines
            break
        self.body(0, None)
        return self.items

    def body(self, i, parent):
        toks, n = self.toks, len(self.toks)
        container = self.items if parent is None else parent.children
        enum_ctx = parent is not None and parent.kind == "enum"
        run_doc = None
        while i < n:
            t = toks[i]
            if t.kind == "p" and t.text == "}":
                return i + 1
            if t.kind == "p" and t.text in (";", ","):
                i += 1
                continue
            first = t
            at_line_start = i == 0 or t.line != toks[i - 1].eline
            doc = self.doc_before(t) if at_line_start else None
            inline_member = (not at_line_start) and parent is not None and parent.one_liner
            attrs = []
            while i < n and toks[i].kind == "p" and toks[i].text == "@":
                s = i
                i += 1
                while i < n and (toks[i].kind == "id" or toks[i].text == "::"):
                    i += 1
                if i < n and toks[i].text == "(" and toks[i].line == toks[i - 1].eline:
                    d = 0
                    while i < n:
                        if toks[i].text == "(":
                            d += 1
                        elif toks[i].text == ")":
                            d -= 1
                            if d == 0:
                                i += 1
                                break
                        i += 1
                attrs.append(join_toks(toks[s:i], self.src))
            if i >= n:
                break
            hs = i
            mods = set()
            while i < n and toks[i].kind == "id" and toks[i].text in MODS and \
                    not (i + 1 < n and toks[i + 1].text == "if"):
                mods.add(toks[i].text)
                i += 1
            if i >= n:
                break
            kw = toks[i].text
            if kw in ("if", "else"):
                j, d = i, 0
                while j < n:
                    tx = toks[j].text
                    if tx in ("(", "["):
                        d += 1
                    elif tx in (")", "]"):
                        d -= 1
                    elif tx == "{" and d == 0:
                        break
                    j += 1
                if j >= n:
                    return n
                i = self.body(j + 1, parent)
                continue
            if kw == "ffi":
                i = self.skip_expr(i + 1, False)
                continue
            kind = kw if (toks[i].kind == "id" and kw in ITEM_KW) else ""
            if kind == "const" and not (i + 2 < n and toks[i + 2].text == ":"):
                kind = ""
            field = False
            if not kind:
                if enum_ctx and toks[i].kind == "id":
                    kind = "case"
                elif toks[i].kind == "id" and i + 1 < n and toks[i + 1].text == ":":
                    kind = "static" if "static" in mods else ("const" if "eval" in mods else "var")
                    field = True
                else:
                    i = self.skip_expr(i + 1, enum_ctx)
                    continue
            if kind == "module" and False:
                pass
            if kind in ITEM_KW and not field:
                i += 1
            if kind in GEN_KW and i < n and toks[i].text == "<":
                d = 0
                while i < n:
                    if toks[i].text == "<":
                        d += 1
                    elif toks[i].text == ">":
                        d -= 1
                        if d == 0:
                            i += 1
                            break
                    i += 1
            name_start = i
            d, term, j = 0, None, i
            import_mode = kind == "import"
            while j < n:
                tj = toks[j]
                x = tj.text if tj.kind == "p" else ""
                if j > i and d == 0 and tj.line != toks[j - 1].eline:
                    if not (toks[j - 1].text in CONT_PREV or tj.text in CONT_NEXT):
                        break
                if x in ("(", "["):
                    d += 1
                elif x in (")", "]"):
                    d -= 1
                elif x == "{":
                    if import_mode or d > 0:
                        d += 1
                    else:
                        term = "{"
                        break
                elif x == "}":
                    if d == 0:
                        break
                    d -= 1
                elif d == 0 and x == ";":
                    break
                elif d == 0 and x == "," and enum_ctx:
                    break
                elif d == 0 and x in ("=", "=>") and kind != "type" and \
                        not (j > 0 and toks[j - 1].text == "op"):
                    term = "="
                    break
                j += 1
            he = j
            item = Item()
            item.file = self.rel
            item.line = first.line
            item.attrs = attrs
            item.parent = parent
            item.kind = kind
            item.pub = "pub" in mods
            sig_toks = [x for x in toks[hs:he] if not (x.kind == "id" and x.text == "pub")]
            item.sig = join_toks(sig_toks, self.src)
            if item.pub and kind == "import":
                item.sig = "pub " + item.sig
            item.name = self.name_of(kind, toks[name_start:he])
            if kind == "extend":
                txt = join_toks(toks[name_start:he], self.src)
                m = re.search(r"\bimpl\b", txt)
                item.target = (txt[:m.start()] if m else txt).strip()
                item.impl = txt[m.end():].strip() if m else ""
                item.name = item.target
            if kind == "import":
                m = re.search(r"\{(.*)\}", join_toks(toks[name_start:he], self.src))
                if m:
                    item.imported = [x.strip() for x in m.group(1).split(",") if x.strip()]
            item.doc = None if inline_member else doc
            if (self.rel, item.name) in INCLUDE_PRIVATE:
                item.pub = True
                item.sig = re.sub(r"\bpriv\s+", "", item.sig)
                item.section = "Operators"
            if kind in ("case", "extend"):
                item.pub = True
            if parent is not None and parent.kind == "interface" and kind in ("fn", "var", "type", "const"):
                item.pub = True
            if kind == "extend" and item.impl:
                if item.doc is None and run_doc is not None:
                    item.doc, item.inherited = run_doc, True
                elif item.doc is not None:
                    run_doc = item.doc
            else:
                run_doc = None
            if term == "{":
                if kind == "module":
                    i = self.body(he + 1, parent)  # transparent: a module block just scopes names
                    continue
                if kind in CONTAINERS:
                    k = self.skip_braces(he)
                    item.one_liner = toks[k - 1].line == toks[he].line
                    if kind == "enum" and item.one_liner:
                        item.sig += " " + join_toks(toks[he:k], self.src)
                        i = k
                    else:
                        i = self.body(he + 1, item)
                        if kind == "enum":
                            self.fold_shared_cases(item)
                else:
                    i = self.skip_braces(he)
            elif term == "=":
                i = self.skip_expr(he + 1, enum_ctx)
            else:
                i = he + (1 if he < n and toks[he].text in (";", ",") else 0)
            if kind in ("module", "test"):
                if i <= hs:
                    i = hs + 1
                continue
            container.append(item)
            if i <= hs:
                i = hs + 1
        return n

    def fold_shared_cases(self, enum):
        """Cases sharing a source line cannot carry a `///` each; they go into the signature."""
        by_line = {}
        for c in enum.children:
            by_line.setdefault(c.line, []).append(c)
        shared = [c for c in enum.children if len(by_line[c.line]) > 1 and c.doc is None]
        if not shared:
            return
        lines = []
        for ln in sorted({c.line for c in shared}):
            lines.append("    " + ", ".join(c.sig for c in by_line[ln] if c in shared) + ",")
        enum.children = [c for c in enum.children if c not in shared]
        enum.sig += " {\n" + "\n".join(lines) + "\n}"

    def name_of(self, kind, nt):
        if not nt:
            return ""
        if kind in ("module", "import"):
            return join_toks(nt, self.src)
        if kind == "fn" and nt[0].text == "op":
            ops = []
            for t in nt[1:]:
                if t.text == "(" and ops:
                    break
                ops.append(t.text)
            return "op " + ("".join(ops) or "()")
        return nt[0].text if nt[0].kind == "id" else join_toks(nt[:1], self.src)


# ------------------------------------------------------------------ doc parsing

TAGS = ("param", "returns", "panics", "safety", "example", "note", "see")


class Doc:
    def __init__(self):
        self.body = []
        self.params = []
        self.sections = OrderedDict()

    @property
    def summary(self):
        para = []
        for l in self.body:
            if not l.strip():
                if para:
                    break
                continue
            para.append(l.strip())
        return " ".join(para)


def parse_doc(lines):
    d = Doc()
    cur = ("body", None)
    infence = False
    for raw in lines:
        l = raw[1:] if raw.startswith(" ") else raw
        l = l.rstrip()
        s = l.strip()
        if s.startswith("```"):
            infence = not infence
        m = None if (infence or s.startswith("```")) else re.match(r"^\s*\\(\w+)\b\s?(.*)$", l)
        if m:
            tag, rest = m.group(1), m.group(2)
            if tag == "param":
                mm = re.match(r"(\S+)\s*(.*)", rest)
                entry = [mm.group(1) if mm else rest, [mm.group(2)] if mm else [""]]
                d.params.append(entry)
                cur = ("param", entry)
                continue
            if tag in ("brief", "detail", "p"):
                d.body.append(rest)
                cur = ("body", None)
                continue
            if tag == "par":
                d.body.append("")
                d.body.append("\x01%s\x02" % rest if rest else "")
                cur = ("body", None)
                continue
            if tag == "class":
                continue
            if tag in TAGS:
                sec = d.sections.setdefault(tag, [])
                sec.append([rest] if rest else [])
                cur = (tag, sec[-1])
                continue
        if cur[0] == "body":
            d.body.append(l)
        elif cur[0] == "param":
            cur[1][1].append(l if infence else s)
        else:
            cur[1].append(l)
    return d


def esc_inline(text):
    """Escape MDX-significant characters outside backtick code spans."""
    parts = re.split(r"(`+[^`]*`+)", text)
    out = []
    for k, p in enumerate(parts):
        if k % 2 == 1:
            out.append(p)
            continue
        p = p.replace("<", "&lt;").replace("{", "&#123;").replace("}", "&#125;")
        p = p.replace("_", "\\_").replace("*", "\\*")
        out.append(p)
    return re.sub(r"(?m)^(\s*)#", r"\1\\#", "".join(out))


def render_prose(lines):
    """Markdown for body/section lines: fences verbatim, indented-after-blank blocks preformatted."""
    chunks = []
    infence = False
    for l in lines:
        if l.strip().startswith("```"):
            if not infence:
                chunks.append([True, [l.strip()]])
                infence = True
            else:
                chunks[-1][1].append("```")
                infence = False
            continue
        if infence:
            chunks[-1][1].append(l)
        elif chunks and not chunks[-1][0]:
            chunks[-1][1].append(l)
        else:
            chunks.append([False, [l]])
    out = []
    for code, ls in chunks:
        if code:
            if ls[-1] != "```" or len(ls) == 1:
                ls.append("```")
            out.append("\n".join(ls))
            continue
        res, k, prev_blank = [], 0, True
        while k < len(ls):
            l = ls[k]
            if prev_blank and l.startswith("    ") and l.strip():
                j, blk = k, []
                while j < len(ls) and (ls[j].startswith("    ") or
                                       (not ls[j].strip() and j + 1 < len(ls) and ls[j + 1].startswith("    "))):
                    blk.append(ls[j])
                    j += 1
                ind = min(len(x) - len(x.lstrip()) for x in blk if x.strip())
                res.append(("code", [x[ind:] for x in blk]))
                k, prev_blank = j, False
                continue
            res.append(("text", [l]))
            prev_blank = not l.strip()
            k += 1
        buf = []
        for kind, ll in res:
            if kind == "text":
                buf += ll
            else:
                if buf:
                    out.append(esc_inline("\n".join(buf)))
                    buf = []
                out.append("```text\n" + "\n".join(ll) + "\n```")
        if buf:
            out.append(esc_inline("\n".join(buf)))
    txt = "\n\n".join(x for x in (c.strip("\n") for c in out) if x.strip())
    return txt.replace("\x01", "**").replace("\x02", "**")


def render_doc(doc_lines):
    if not doc_lines:
        return ""
    d = parse_doc(doc_lines)
    parts = []
    body = d.body
    while body and not body[0].strip():
        body = body[1:]
    if body:
        parts.append(render_prose(body))
    if d.params:
        rows = ["- `%s`: %s" % (nm, esc_inline(" ".join(x for x in ls if x).strip())) for nm, ls in d.params]
        parts.append("**Parameters**\n\n" + "\n".join(rows))
    for tag, label in (("returns", "Returns"), ("panics", "Panics"), ("safety", "Safety")):
        for ls in d.sections.get(tag, []):
            parts.append("**%s**\n\n%s" % (label, render_prose(ls)))
    for ls in d.sections.get("example", []):
        if not any("```" in x for x in ls):
            ls = ["```kairo"] + ls + ["```"]
        parts.append("**Example**\n\n" + render_prose(ls))
    for ls in d.sections.get("note", []):
        parts.append("**Notes**\n\n" + render_prose(ls))
    for ls in d.sections.get("see", []):
        parts.append("**See also**\n\n" + render_prose(ls))
    return "\n\n".join(p for p in parts if p.strip())


def wrap_sig(sig, width=100):
    """Break a long signature one parameter per line."""
    if len(sig) > width and "import" in sig and "{" in sig:
        head, _, rest = sig.partition("{")
        names = [x.strip() for x in rest.rstrip("} ").split(",") if x.strip()]
        lines, cur = [], "   "
        for nm in names:
            if len(cur) + len(nm) + 2 > width - 4:
                lines.append(cur.rstrip())
                cur = "   "
            cur += " " + nm + ","
        lines.append(cur.rstrip())
        return head + "{\n" + "\n".join("    " + l.strip() for l in lines) + "\n}"
    if len(sig) <= width or "(" not in sig:
        return sig
    s = sig.replace("op ()", "op \x00\x01", 1)
    ang, po = 0, -1
    for k, ch in enumerate(s):
        if ch == "<":
            ang += 1
        elif ch == ">" and s[k - 1] not in "-=":
            ang = max(0, ang - 1)
        elif ch == "(" and ang == 0:
            po = k
            break
    if po < 0:
        return sig
    d, args, cur, pc = 0, [], "", -1
    for k in range(po + 1, len(s)):
        ch = s[k]
        if ch in "([{<":
            d += 1
        elif ch in ")]}":
            if d == 0:
                pc = k
                break
            d -= 1
        elif ch == ">" and s[k - 1] not in "-=":
            d = max(0, d - 1)
        if ch == "," and d == 0:
            args.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if pc < 0:
        return sig
    if cur.strip():
        args.append(cur.strip())
    if not args:
        return sig
    out = s[:po + 1] + "\n" + ",\n".join("    " + a for a in args) + "\n" + s[pc:]
    return out.replace("\x00\x01", "()")


# ----------------------------------------------------------------- slug / text


def slug(text, seen):
    """github-slugger, which Astro uses for heading ids."""
    s = "".join(c for c in text.lower() if c.isalnum() or c in "_- ").replace(" ", "-")
    if s in seen:
        seen[s] += 1
        out = "%s-%d" % (s, seen[s])
        while out in seen:
            seen[s] += 1
            out = "%s-%d" % (s, seen[s])
        seen[out] = 0
        return out
    seen[s] = 0
    return s


def yq(s):
    return json.dumps(s, ensure_ascii=False)


def one_line(s, limit=160):
    s = re.sub(r"\s+", " ", s).replace("`", "").strip()
    if len(s) > limit:
        cut = s.rfind(" ", 0, limit - 1)
        s = s[:cut if cut > 40 else limit - 1] + "..."
    return s


def summary_cell(doc_lines):
    if not doc_lines:
        return ""
    sm = parse_doc(doc_lines).summary
    m = re.search(r"[.!?](\s|$)", sm)
    if m and m.end() < len(sm) and m.end() > 20:
        sm = sm[:m.end()].strip()
    return esc_inline(sm).replace("|", "\\|")


def banner_text(lines):
    """Prose of a `/// --- The Kairo Project --- ///` file header."""
    if not lines:
        return []
    out, started = [], False
    for raw in lines[1:]:
        l = raw.rstrip()
        s = l.strip()
        if s.startswith("---") or re.match(r"^-+\s*/*$", s):
            break
        if s.startswith(("SPDX", "Copyright", "Part of the", "See:")):
            if started:
                break
            continue
        if not started and not s:
            continue
        started = True
        out.append(l)
    ind = min([len(x) - len(x.lstrip()) for x in out if x.strip()] or [0])
    out = [x[ind:] if x.strip() else "" for x in out]
    while out and not out[-1].strip():
        out.pop()
    return out


# ------------------------------------------------------------------ collection


class FileInfo:
    def __init__(self, rel, items, banner):
        self.rel, self.items, self.banner = rel, items, banner


def walk_public(items, parent=None):
    for it in items:
        if it.pub:
            yield it
            if it.kind in CONTAINERS:
                yield from walk_public(it.children, it)


def doc_required(it):
    if it.kind in ("extend", "import"):
        return False
    p = it.parent
    if p is not None and p.kind == "extend" and p.impl:
        return False
    if p is not None and p.one_liner and p.kind in ("class", "struct", "extend"):
        return False
    return True


def collect_interfaces(files):
    out = {}

    def rec(items):
        for it in items:
            if it.kind == "interface":
                out[it.name] = {c.name: c.doc for c in it.children if c.kind == "fn" and c.doc}
            rec(it.children)
    for f in files:
        rec(f.items)
    return out


def apply_inheritance(files, ifaces):
    def rec(items):
        for it in items:
            if it.kind == "extend" and it.impl:
                m = re.match(r"[A-Za-z_]\w*", it.impl)
                iname = m.group(0) if m else ""
                for ch in it.children:
                    if ch.doc is None:
                        if it.doc is not None and it.one_liner:
                            ch.doc, ch.inherited = it.doc, True
                        elif iname in ifaces and ch.name in ifaces[iname]:
                            ch.doc, ch.inherited = ifaces[iname][ch.name], True
                if it.doc is None and iname in ifaces:
                    ms = [c.doc for c in it.children if c.doc]
                    if ms:
                        it.doc, it.inherited = ms[0], True
            rec(it.children)
    for f in files:
        rec(f.items)


# ------------------------------------------------------------------- rendering


class Entry:
    def __init__(self, kind, level, text, item=None, body=""):
        self.kind, self.level, self.text, self.item, self.body = kind, level, text, item, body
        self.slug = ""


def heading_name(it):
    if it.kind == "extend":
        return "extend " + it.target + ((" impl " + it.impl) if it.impl else "")
    p = it.parent
    if p is not None:
        return "%s.%s" % (p.target if p.kind == "extend" else p.name, it.name)
    return it.name


def item_entries(it, level, out):
    sig = "\n".join(it.attrs + [wrap_sig(it.sig)])
    body = "```kairo\n%s\n```" % sig
    if it.doc:
        r = render_doc(it.doc)
        if r:
            body += "\n\n" + r
    out.append(Entry("item", min(level, 4), heading_name(it), it, body))
    if it.kind in CONTAINERS and not (it.kind == "enum" and it.one_liner):
        for c in it.children:
            if c.pub:
                item_entries(c, level + 1, out)


def build_entries(items, links):
    entries = []
    groups = OrderedDict()
    for it in items:
        if it.kind == "extend" and it.impl and it.target in PRIMS and len(it.children) <= 1:
            groups.setdefault(it.impl, []).append(it)
    table_impls = {k for k, v in groups.items() if len(v) >= 3}
    done = set()
    cur_section = ""
    imports = [it for it in items if it.kind == "import" and it.doc]
    for it in items:
        if it.kind == "import":
            continue
        if it.kind == "extend" and it.impl in table_impls and it.target in PRIMS and len(it.children) <= 1:
            if it.impl in done:
                continue
            done.add(it.impl)
            rows = []
            for g in groups[it.impl]:
                d = g.doc or (g.children[0].doc if g.children else None)
                txt = " ".join(x.strip() for x in parse_doc(d).body if x.strip()) if d else ""
                rows.append("| `%s` | %s |" % (g.target, esc_inline(txt).replace("|", "\\|")))
            iname = re.match(r"[A-Za-z_]\w*", it.impl).group(0)
            body = ("Each primitive type implements `%s` as follows.\n\n| Type | How it hashes |\n| --- | --- |\n"
                    % iname) + "\n".join(rows)
            entries.append(Entry("table", 2, "%s implementations for primitives" % iname, None, body))
            continue
        if it.section and it.section != cur_section:
            cur_section = it.section
            entries.append(Entry("section", 2, it.section, None, POW_NOTE))
        item_entries(it, 3 if it.section else 2, entries)
    if imports:
        blocks = []
        for it in imports:
            blk = "```kairo\n%s\n```" % wrap_sig(it.sig)
            if it.doc:
                blk += "\n\n" + render_doc(it.doc)
            if it.imported:
                names = []
                for nm in it.imported:
                    ln = links.get(nm)
                    names.append("[`%s`](%s)" % (nm, ln) if ln else "`%s`" % nm)
                blk += "\n\nRe-exported items: " + ", ".join(names) + "."
            blocks.append(blk)
        entries.append(Entry("reexports", 2, "Re-exports", None, "\n\n".join(blocks)))
    seen = {}
    for e in entries:
        e.slug = slug(e.text, seen)
    return entries


def emit_page(title, desc, sources, intro, entries, order):
    L = ["---", "title: %s" % yq(title), "description: %s" % yq(desc), "sidebarLabel: %s" % yq(title),
         "order: %d" % order, "---", "",
         "{/* %s from %s. Do not edit by hand: edit the doc comments and re-run it. */}" %
         (GENERATED_MARK, ", ".join(sources)), ""]
    if intro:
        L += [intro, ""]
    tops = [e for e in entries if e.level == 2]
    if len(tops) > 1:
        L += ["## Contents", "", "| Name | Summary |", "| --- | --- |"]
        for e in tops:
            sm = ""
            if e.item is not None and e.item.doc:
                sm = summary_cell(e.item.doc)
            elif e.kind == "table":
                sm = "How each primitive type implements the interface."
            nm = "`%s`" % e.text if e.kind == "item" else e.text
            L.append("| [%s](#%s) | %s |" % (nm, e.slug, sm))
        L.append("")
    for e in entries:
        head = "#" * e.level + " " + ("`%s`" % e.text if e.kind == "item" else e.text)
        L += [head, "", e.body, ""]
    return "\n".join(L).rstrip("\n") + "\n"


# ------------------------------------------------------------------------ main


def read_lib(root, sub):
    base = root / sub
    files = []
    if not base.is_dir():
        return files
    for p in sorted(base.rglob("*.k")):
        rel = p.relative_to(base).as_posix()
        if re.search(r"(^|/)v\d+draft\.k$", rel) or ".test." in rel:
            continue
        ps = Parser(p.read_text(encoding="utf-8"), rel)
        files.append(FileInfo(rel, ps.parse(), ps.banner))
    return files


def core_area(kind, rel):
    if kind == "macro":
        return "macros"
    if rel in CORE_FILE_AREA:
        return CORE_FILE_AREA[rel]
    d = rel.split("/")[0] if "/" in rel else ""
    return CORE_DIR_AREA.get(d, "other")


def page_intro(files):
    parts = []
    for f in files:
        bt = banner_text(f.banner)
        txt = render_doc(bt) if bt else ""
        if txt:
            parts.append(txt if len(files) == 1 else "*%s*\n\n%s" % (f.rel, txt))
    return "\n\n".join(parts)


def main():
    ap = argparse.ArgumentParser(description="Generate library reference MDX pages (interim extractor).")
    ap.add_argument("--lib", default="Lib")
    ap.add_argument("--web", default=str(Path(__file__).resolve().parent.parent.parent / "kairo-web"),
                    help="the website checkout (default: the sibling of this repository)")
    ap.add_argument("--allow-undocumented", action="store_true")
    a = ap.parse_args()
    lib = Path(a.lib)
    out_root = Path(a.web) / "src/content/docs/library"

    core_files = read_lib(lib, "builtin")
    std_files = read_lib(lib, "std")
    apply_inheritance(core_files + std_files, collect_interfaces(core_files + std_files))

    undoc = OrderedDict()
    for prefix, files in (("", core_files), ("std/", std_files)):
        for f in files:
            for it in walk_public(f.items):
                if doc_required(it) and it.doc is None:
                    undoc.setdefault(prefix + f.rel, []).append("%d: %s" % (it.line, heading_name(it)))

    # ---- assign items to pages
    core_pages = OrderedDict((k, {"files": [], "items": []}) for k in CORE_AREAS)
    for f in core_files:
        for it in f.items:
            if not it.pub or (it.kind == "import" and f.rel != "module.k"):
                continue
            pg = core_pages[core_area(it.kind, f.rel)]
            if f.rel not in pg["files"]:
                pg["files"].append(f.rel)
            pg["items"].append(it)
    jobs = []
    for order, (area, pg) in enumerate(core_pages.items(), 1):
        if pg["items"]:
            pg["banners"] = [f for f in core_files if f.rel in pg["files"] and core_area("", f.rel) == area]
            jobs.append(("core", area, pg, order))
    root_items, root_file, std_pages = [], None, {}
    for f in std_files:
        if f.rel == "module.k":
            root_file = f
            root_items = [it for it in f.items if it.kind == "import" and it.pub]
            continue
        items = [it for it in f.items if it.pub]
        if items:
            std_pages[f.rel[:-2].replace("/", "-").lower()] = (f, items)
    for order, (sl, (f, items)) in enumerate(sorted(std_pages.items(), key=lambda kv: (
            STD_ORDER.index(kv[0]) if kv[0] in STD_ORDER else 99, kv[0])), 1):
        jobs.append(("std", sl, {"files": [f.rel], "items": items, "banners": [f]}, order))

    # ---- two passes: the first learns anchors, the second resolves re-export links
    links = {}
    built = OrderedDict()
    for _ in range(2):
        for sect, key, pg, order in jobs:
            entries = build_entries(pg["items"], links)
            built[(sect, key)] = (pg, entries, order)
        links = {}
        for (sect, key), (pg, entries, order) in built.items():
            url = "/docs/library/%s/%s/" % (sect, key)
            for e in entries:
                if e.item is not None and e.item.parent is None and e.item.kind != "extend" \
                        and e.item.name not in links:
                    links[e.item.name] = "%s#%s" % (url, e.slug)

    # ---- write
    written = []

    def write(path, text):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(path)

    for d in ("core", "std"):
        dd = out_root / d
        if dd.is_dir():
            for p in dd.glob("*.mdx"):
                if GENERATED_MARK in p.read_text(encoding="utf-8"):
                    p.unlink()

    core_rows, std_rows = [], []
    for (sect, key), (pg, entries, order) in built.items():
        # core file headers are implementation notes; only std's are user-facing
        intro = ""
        if sect == "core":
            title, blurb = CORE_AREAS[key]
            srcs = ["Lib/builtin/" + r for r in pg["files"]]
            desc = blurb
            intro = blurb
            core_rows.append((title, key, blurb))
        else:
            f = pg["banners"][0]
            title = "std::" + f.rel[:-2].replace("/", "::")
            srcs = ["Lib/std/" + f.rel]
            desc = STD_BLURBS.get(key, title)
            intro = desc
            std_rows.append((title, key, desc))
        write(out_root / sect / (key + ".mdx"), emit_page(title, desc, srcs, intro, entries, order))

    def index_page(title, desc, rows, base, order, intro, extra=""):
        L = ["---", "title: %s" % yq(title), "description: %s" % yq(desc), "sidebarLabel: %s" % yq(title),
             "order: %d" % order, "---", "", "{/* %s. Do not edit by hand. */}" % GENERATED_MARK, "", intro, ""]
        if rows:
            L += ["| Page | Contents |", "| --- | --- |"]
            for t, k, b in rows:
                L.append("| [%s](/docs/library/%s%s/) | %s |" % (t.replace("|", "\\|"), base, k, esc_inline(b)))
            L.append("")
        if extra:
            L += [extra, ""]
        return "\n".join(L).rstrip("\n") + "\n"

    write(out_root / "core" / "index.mdx", index_page(
        "Core library", "Reference for Kairo's builtin (core) library, the implicit prelude.", core_rows, "core/", 1,
        "The core library (`Lib/builtin`) is the implicit prelude: every file sees these types, functions and "
        "macros without an import. The compiler lowers `[T]`, `T?`, ranges, f-strings, `panic` results and "
        "generators to the declarations documented here."))
    root_extra = ""
    if root_file is not None:
        parts = []
        for it in root_items:
            blk = "```kairo\n%s\n```" % it.sig
            if it.doc:
                blk += "\n\n" + render_doc(it.doc)
            parts.append(blk)
        if parts:
            root_extra = "## Root re-exports\n\n" + "\n\n".join(parts)
    write(out_root / "std" / "index.mdx", index_page(
        "Standard library", "Reference for Kairo's standard library (std).", std_rows, "std/", 2,
        "The standard library (`Lib/std`) is an ordinary Kairo library named `kairo::std`, spelled `std`. "
        "Nothing in it is implicit: write `import std::io` and call `io::println`.", root_extra))
    write(out_root / "index.mdx", index_page(
        "Library reference", "Reference for the Kairo core and standard libraries, generated from doc comments.",
        [("Core library", "core", "The implicit prelude: containers, strings, memory, errors, intrinsics."),
         ("Standard library", "std", "Explicitly imported modules: I/O, environment, memory, C types.")],
        "", 0, "Library reference pages are generated from the `///` doc comments in the library sources."))

    print("wrote %d pages under %s" % (len(written), out_root))
    total = 0
    for k, v in undoc.items():
        print("undocumented %-32s %d" % (k, len(v)))
        for x in v:
            print("    %s" % x)
        total += len(v)
    if total:
        msg = "%d undocumented pub declaration(s)" % total
        if a.allow_undocumented:
            print("warning: " + msg)
        else:
            print("error: " + msg, file=sys.stderr)
            return 1
    else:
        print("all pub declarations documented")
    return 0


if __name__ == "__main__":
    sys.exit(main())
